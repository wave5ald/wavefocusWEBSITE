const dictionaries = { en, ar };
let current = 'en';

export function setLanguage(lang) {
  current = dictionaries[lang] ? lang : 'en';
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
}

export const getLanguage = () => current;

export function t(key, vars) {
  const dict = dictionaries[current] || en;
  let value = dict[key];
  if (value == null) value = en[key];
  if (value == null) return key;
  return fill(value, vars);
}

/** Plural-aware lookup: prefers the `<key>One` entry when n === 1. */
export function tn(key, n, vars) {
  const dict = dictionaries[current] || en;
  const singular = `${key}One`;
  const useSingular = Number(n) === 1 && (dict[singular] != null || en[singular] != null);
  return t(useSingular ? singular : key, { n, ...(vars || {}) });
}

function fill(value, vars) {
  if (vars) {
    value = String(value).replace(/\{(\w+)\}/g, (match, name) =>
      Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
    );
  }
  return value;
}

/** Category / time-slot labels are also dictionary keys. */
export const categoryLabel = (name) => t(name);
export const slotLabel = (name) => t(name);
